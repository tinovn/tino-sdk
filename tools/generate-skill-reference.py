#!/usr/bin/env python3
"""Generate skills/tino-userapi/references/resource-map.md from the catalog.

Keeps the endpoint list an agent reads in step with the endpoints the SDKs expose.

Usage:
    python3 tools/generate-skill-reference.py
"""
from __future__ import annotations

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from sdkgen import catalog as cat  # noqa: E402

# Same reading order as the documentation chapters.
GROUP_ORDER = [
    "auth", "account", "billing", "support", "domains", "dns", "services", "cpanel",
    "vms", "cart", "certificates", "affiliate", "security", "location", "languages",
    "ekyc", "tinosite",
]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalog", default=os.path.join(ROOT, "spec", "tino-userapi-catalog.json"))
    parser.add_argument("--out", default=os.path.join(
        ROOT, "skills", "tino-userapi", "references", "resource-map.md"))
    args = parser.parse_args()

    catalog = cat.load(args.catalog)
    grouped = cat.by_group(catalog)

    lines = [
        "# Resource map",
        "",
        "What lives in each group, and the Python method name. Node and PHP use the same",
        "names in `camelCase`. *live* means the response shape in the contract docs was",
        "captured from a real call; the rest are documented but were not exercised.",
        "",
        "Generated by tools/generate-skill-reference.py — do not edit by hand.",
        "",
    ]

    ordered = [g for g in GROUP_ORDER if g in grouped]
    ordered += [g for g in sorted(grouped) if g not in GROUP_ORDER]

    for group in ordered:
        operations = sorted(grouped[group], key=lambda op: (op["path"], op["method"]))
        live = sum(1 for op in operations if op.get("verified") == "live")
        lines += [
            f"## `client.{cat.snake(group)}` — {cat.GROUP_TITLES.get(group, group)}",
            "",
            f"{len(operations)} operations, {live} verified live.",
            "",
            "| Method | Endpoint | Python | Auth |",
            "| --- | --- | --- | --- |",
        ]
        for operation in operations:
            suffix = " *(deprecated)*" if operation.get("deprecated") else ""
            auth = "Bearer" if operation.get("auth") else "public"
            lines.append(
                f"| `{operation['method']}` | `{operation['path']}` | "
                f"`{cat.python_method(operation['name'])}()`{suffix} | {auth} |"
            )
        lines.append("")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines).rstrip() + "\n")
    print(f"{len(catalog['operations'])} operations -> {args.out}")


if __name__ == "__main__":
    main()
