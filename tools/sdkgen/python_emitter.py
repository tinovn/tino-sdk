"""Emit the Python resource layer from the catalog."""
from __future__ import annotations

import os
from typing import Any, Dict, List

from . import catalog as cat

HEADER = '''"""{title}.

Generated from spec/tino-userapi-catalog.json by tools/generate-sdk.py — do not edit by hand.
"""
from __future__ import annotations

from typing import Any, Optional

from .base import Resource


class {class_name}(Resource):
    """{title} — {count} operations."""
'''


def _signature(operation: Dict[str, Any]) -> tuple[str, List[str], str]:
    """Return the argument list and the statements that build the request."""
    args: List[str] = ["self"]
    for param in cat.path_params(operation):
        args.append(cat.python_arg(param["name"]))

    query = operation.get("query") or []
    keyword_args: List[str] = []
    query_map: List[str] = []
    for param in query:
        name = param["name"]
        arg = "filters" if name == "filter" else cat.python_arg(name)
        default = "None"
        keyword_args.append(f"{arg}: Any = {default}")
        query_map.append(f'"{name}": {arg}')

    # The explicit payload argument must not collide with a body field of the same
    # name — POST /tickets really does have a field called "body".
    payload_arg = "payload"
    field_names = {f["name"] for f in cat.body_fields(operation)}
    while payload_arg in field_names:
        payload_arg += "_"
    if cat.has_body(operation):
        keyword_args.append(f"{payload_arg}: Optional[dict] = None")

    if keyword_args:
        args.append("*")
        args.extend(keyword_args)

    body_call = ""
    if cat.has_body(operation):
        args.append("**fields: Any")
        body_call = f"body=self._body({payload_arg}, fields), "
    else:
        args.append("**query: Any")   # free-form query string parameters

    return ", ".join(args), query_map, body_call


def _method(operation: Dict[str, Any]) -> List[str]:
    name = cat.python_method(operation["name"])
    signature, query_map, body_call = _signature(operation)

    lines = [f"    def {name}({signature}) -> Any:"]
    doc = cat.doc_lines(operation)
    lines.append('        """' + doc[0])
    rest = doc[1:]
    while rest and not rest[0].strip():
        rest.pop(0)
    if rest:
        lines.append("")
        lines.extend(cat.indent(rest, "        "))
    lines.append('        """')

    params = cat.path_params(operation)
    if params:
        assignments = ", ".join(f'{p["name"]}={cat.python_arg(p["name"])}' for p in params)
        lines.append(f'        path = self._path("{operation["path"]}", {assignments})')
        path_expr = "path"
    else:
        path_expr = f'"{operation["path"]}"'

    if query_map:
        explicit = "{" + ", ".join(query_map) + "}"
        extra = "{}" if cat.has_body(operation) else "query"
        lines.append(f"        params = self._query({explicit}, {extra})")
        query_expr = "query=params, "
    elif cat.has_body(operation):
        query_expr = ""
    else:
        query_expr = "query=query, "

    auth = "" if operation.get("auth", True) else "authenticated=False, "
    call = f'        return self._call("{operation["method"]}", {path_expr}, {query_expr}{body_call}{auth})'
    lines.append(call.replace(", )", ")"))
    lines.append("")
    return lines


def _prune(out_dir: str, keep: set) -> None:
    """Delete generated files for groups the catalog no longer contains."""
    for name in os.listdir(out_dir):
        if name not in keep and os.path.isfile(os.path.join(out_dir, name)):
            os.remove(os.path.join(out_dir, name))


def emit(catalog: Dict[str, Any], root: str) -> List[str]:
    grouped = cat.by_group(catalog)
    out_dir = os.path.join(root, "sdk", "python", "tino_userapi", "resources")
    os.makedirs(out_dir, exist_ok=True)
    written: List[str] = []

    for group, operations in sorted(grouped.items()):
        class_name = cat.pascal(group) + "Resource"
        title = cat.GROUP_TITLES.get(group, group)
        lines = [HEADER.format(title=title, class_name=class_name, count=len(operations))]
        for operation in operations:
            lines.extend(_method(operation))
        # Body helper lives on the base class; declared here for readability of imports.
        path = os.path.join(out_dir, cat.snake(group) + ".py")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines).rstrip() + "\n")
        written.append(path)

    index = ['"""Resource groups exposed on :class:`~tino_userapi.client.TinoClient`.',
             "",
             "Generated by tools/generate-sdk.py — do not edit by hand.",
             '"""',
             "from __future__ import annotations",
             "",
             "from .base import Resource"]
    for group in sorted(grouped):
        index.append(f"from .{cat.snake(group)} import {cat.pascal(group)}Resource")
    index.append("")
    index.append("# Attribute name on the client -> resource class.")
    index.append("RESOURCE_CLASSES = {")
    for group in sorted(grouped):
        index.append(f'    "{cat.snake(group)}": {cat.pascal(group)}Resource,')
    index.append("}")
    index.append("")
    index.append("__all__ = [")
    index.append('    "Resource",')
    index.append('    "RESOURCE_CLASSES",')
    for group in sorted(grouped):
        index.append(f'    "{cat.pascal(group)}Resource",')
    index.append("]")
    _prune(out_dir, {os.path.basename(p) for p in written} | {"base.py", "__init__.py"})
    index_path = os.path.join(out_dir, "__init__.py")
    with open(index_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(index) + "\n")
    written.append(index_path)
    return written
